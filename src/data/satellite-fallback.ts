export function createFallbackSatelliteFeed(): SatelliteFeed {
  const updatedAt = SATELLITE_FALLBACK_RECORDS.reduce(
    (latest, record) => (record.EPOCH > latest ? record.EPOCH : latest),
    "",
  );

  return {
    provider: "CelesTrak",
    mode: "fallback",
    sourceUrl: CELESTRAK_RESOURCE_URL,
    updatedAt,
    servedAt: new Date().toISOString(),
    stale: Date.now() - Date.parse(updatedAt) > 7 * 24 * 60 * 60 * 1_000,
    records: SATELLITE_FALLBACK_RECORDS,
  };
}
