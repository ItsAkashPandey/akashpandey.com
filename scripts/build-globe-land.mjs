// Builds the land mask for the home page globe (src/components/globe/land.ts).
//
// The globe draws a dot at each point of an evenly spread "Fibonacci" grid
// that falls on land. Instead of shipping the dots, this stores one bit per
// grid point (about 5 KB); the browser rebuilds the grid with the same
// formula and keeps the points whose bit is set.
//
// Land comes from Natural Earth's 1:50m coastlines (public domain) via the
// world-atlas package. Only needed again if the grid size changes:
//   node scripts/build-globe-land.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import sharp from "sharp";
import { feature } from "topojson-client";

const POINTS = 40_000;
const WIDTH = 4096;
const HEIGHT = 2048;
const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));
const TAU = Math.PI * 2;

const require = createRequire(import.meta.url);
const topology = JSON.parse(
  readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"),
);
const land = feature(topology, topology.objects.land);

const x = (lon) => (((lon + 180) / 360) * WIDTH).toFixed(1);
const y = (lat) => (((90 - lat) / 180) * HEIGHT).toFixed(1);
const ring = (points) =>
  points.map(([lon, lat], i) => `${i ? "L" : "M"}${x(lon)} ${y(lat)}`).join("") + "Z";

const paths = [];
for (const { geometry } of land.features) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) paths.push(polygon.map(ring).join(""));
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}"><rect width="100%" height="100%" fill="#000"/><path fill="#fff" fill-rule="evenodd" d="${paths.join("")}"/></svg>`;
const { data } = await sharp(Buffer.from(svg))
  .greyscale()
  .raw()
  .toBuffer({ resolveWithObject: true });

// Same grid as gridPoint() in src/components/globe/globe-scene.ts.
const bits = new Uint8Array(Math.ceil(POINTS / 8));
let onLand = 0;
for (let i = 0; i < POINTS; i += 1) {
  const lat = (Math.asin(1 - ((i + 0.5) * 2) / POINTS) * 180) / Math.PI;
  const lon = (((i * GOLDEN_ANGLE) % TAU) - Math.PI) * (180 / Math.PI);
  const px = Math.min(WIDTH - 1, Math.floor(((lon + 180) / 360) * WIDTH));
  const py = Math.min(HEIGHT - 1, Math.floor(((90 - lat) / 180) * HEIGHT));
  if (data[py * WIDTH + px] > 127) {
    bits[i >> 3] |= 1 << (i & 7);
    onLand += 1;
  }
}

writeFileSync(
  "src/components/globe/land.ts",
  `// Generated by scripts/build-globe-land.mjs from Natural Earth (public domain).
// One bit per point of a ${POINTS}-point Fibonacci grid; ${onLand} are on land.
export const GRID_POINTS = ${POINTS};
export const LAND_MASK = "${Buffer.from(bits).toString("base64")}";
`,
);
console.log(`[globe] ${onLand} of ${POINTS} grid points on land`);
